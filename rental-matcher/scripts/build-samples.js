#!/usr/bin/env node
// Embeds data/sample-*.csv into src/sample-data.js so the app's "Load sample
// data" button works even when index.html is opened straight from disk.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, 'data', f), 'utf8');
const out = `// Generated by scripts/build-samples.js from data/*.csv — do not edit by hand.
(function (root) {
  const data = {
    units: ${JSON.stringify(read('sample-units.csv'))},
    applicants: ${JSON.stringify(read('sample-applicants.csv'))},
  };
  if (typeof module === 'object' && module.exports) module.exports = data;
  else (root.RM = root.RM || {}).sampleData = data;
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(root, 'src', 'sample-data.js'), out);
console.log('Wrote src/sample-data.js');
