  function tIn(l, s, vars) {
    if (s == null) return s;
    const key = String(s);
    return fill(l === 'pt' && PT[key] != null ? PT[key] : key, vars);
  }
  const t = (s, vars) => tIn(lang, s, vars);

  function setLang(l) {
    lang = l === 'pt' ? 'pt' : 'en';
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
      // Static page text marked with data-i18n (its English text is the key).
      document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.innerHTML.trim();
        el.innerHTML = t(el.dataset.i18nKey);
      });
    }
    return lang;
  }

